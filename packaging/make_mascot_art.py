"""Rebuild src/mascot_art.py (the small animation at the bottom of the left panel) from two videos.
Usage: python packaging/make_mascot_art.py animation.mp4 animation_dark.mp4
Needs ffmpeg/ffprobe on PATH and Pillow.

Each frame becomes "ink" (0 = nothing, 255 = full line colour), downscaled (the dark one also
softened at the edges) and reduced to 16 grey levels; near-identical frames are merged (their times
added up). The app paints the ink in the current theme colours, so one asset fits any palette."""
import base64
import io
import subprocess
import sys
import tempfile
from pathlib import Path

from PIL import Image, ImageChops, ImageFilter, ImageStat

HEIGHT = 150  # stored size = shown size at 100 % (the app never needs it bigger than ~1.3x)
LEVELS = 16
SAME = 1.5    # mean frame difference (0-255) below which two frames count as the same


def frames(video):
    """[(PIL frame, duration ms)] with the video's own timing (no duplicated frames)."""
    out = subprocess.run(["ffprobe", "-v", "error", "-select_streams", "v", "-show_entries",
                          "frame=pts_time", "-of", "csv=p=0", str(video)], capture_output=True, text=True,
                         check=True).stdout.split()
    pts = [float(x.strip(",")) for x in out]
    end = float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of",
                                "csv=p=0", str(video)], capture_output=True, text=True, check=True).stdout)
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(["ffmpeg", "-v", "error", "-i", str(video), "-fps_mode", "passthrough",
                        str(Path(tmp) / "%03d.png")], check=True)
        ims = [Image.open(p).convert("L") for p in sorted(Path(tmp).glob("*.png"))]
        for im in ims: im.load()
    times = [b - a for a, b in zip(pts, pts[1:] + [end])]
    return [(im, max(20, round(t * 1000))) for im, t in zip(ims, times)]


def ink(im, dark):
    """Line intensity: the light video has dark lines on paper, the dark one light shapes on black."""
    if not dark: im = ImageChops.invert(im)
    lo, hi = (24, 235) if dark else (10, 220)  # paper / background noise to 0, lines to full
    im = im.point(lambda v: max(0, min(255, round((v - lo) * 255 / (hi - lo)))))
    w = round(im.width * HEIGHT / im.height)
    im = im.resize((w, HEIGHT), Image.LANCZOS)
    if not dark:  # the sketch already ends in white paper: keep its lines sharp to the edge
        step = 255 / (LEVELS - 1)
        return im.point(lambda v: round(round(v / step) * step))
    # dark: soft edges, so the speed lines do not end in a hard frame on the panel
    edge = max(6, HEIGHT // 8)
    mask = Image.new("L", im.size, 0)
    mask.paste(255, (edge, edge, im.width - edge, im.height - edge))
    mask = mask.filter(ImageFilter.GaussianBlur(edge / 2))
    im = ImageChops.multiply(im, mask)
    step = 255 / (LEVELS - 1)
    return im.point(lambda v: round(round(v / step) * step))


def build(video, dark):
    out = []
    for im, ms in frames(video):
        im = ink(im, dark)
        if out and ImageStat.Stat(ImageChops.difference(out[-1][0], im)).mean[0] < SAME:
            out[-1][1] += ms  # merge
        else:
            out.append([im, ms])
    w, h = out[0][0].size
    strip = Image.new("L", (w * len(out), h))
    for i, (im, _) in enumerate(out): strip.paste(im, (i * w, 0))
    buf = io.BytesIO(); strip.save(buf, "PNG", optimize=True)
    return (w, h), [ms for _, ms in out], base64.b64encode(buf.getvalue()).decode()


def main(light, dark):
    lines = ['"""Small looping animation for the bottom of the left panel: one for the light theme, one for the dark.',
             'Generated by packaging/make_mascot_art.py. Each entry: frame size, frame times (ms) and a',
             'grey PNG strip of the frames side by side (white = line colour, black = panel colour)."""',
             "MASCOT = {"]
    for name, video in (("light", light), ("dark", dark)):
        size, times, b64 = build(video, name == "dark")
        lines.append('    "{0}": ({1}, {2}, ('.format(name, size, times))
        lines += ['        "{0}"'.format(b64[i:i + 100]) for i in range(0, len(b64), 100)]
        lines.append("    )),")
        print("{0}: {1} frames {2}, {3} KB".format(name, len(times), size, len(b64) * 3 // 4 // 1024))
    lines.append("}")
    target = Path(__file__).resolve().parent.parent / "src" / "mascot_art.py"
    target.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print("written", target)


if __name__ == "__main__":
    main(*sys.argv[1:3])
